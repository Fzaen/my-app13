<?php
$sql = "SELECT 
    distinct BTR_PRDCD AS PLU,
    DESK, FRC, FLAG, T_IGR, T_IDM, SELF_LIFE, SAT1,
    TURUN_PAJANG, RETUR_SUPP, BATAS_RETUR_SUPP, UPDATE_TGL
FROM (
    SELECT 
        distinct BTR_PRDCD AS BTR_PRDCD,
        BRC_BARCODE,
        PRD_DESKRIPSIPANJANG AS DESK,
        PRD_FRAC AS FRC,
        CASE  
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'N' AND PRD_FLAGOMI = 'N' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_ONLY'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'N' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_IDM'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'N' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_OMI'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'N' AND PRD_FLAGOMI = 'N' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_ONLY'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_IDM_OMI_OBI'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_IDM_OMI'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'N' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_IDM'
            WHEN PRD_FLAGIGR = 'Y' AND PRD_FLAGIDM = 'N' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IGR_OMI_OBI'
            WHEN PRD_FLAGIGR = 'N' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'N' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IDM_ONLY'
            WHEN PRD_FLAGIGR = 'N' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IDM_OMI'
            WHEN PRD_FLAGIGR = 'N' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'N' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IDM_ONLY'
            WHEN PRD_FLAGIGR = 'N' AND PRD_FLAGIDM = 'Y' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'IDM_OMI_OBI'
            WHEN PRD_FLAGIGR = 'N' AND PRD_FLAGIDM = 'N' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'N' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'OMI_ONLY'
            WHEN PRD_FLAGIGR = 'N' AND PRD_FLAGIDM = 'N' AND PRD_FLAGOMI = 'Y' AND PRD_FLAGOBI = 'Y' AND SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) <> '*' THEN 'OMI_OBI'
