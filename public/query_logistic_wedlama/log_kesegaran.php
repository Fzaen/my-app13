            WHEN SUBSTRING(PRD_DESKRIPSIPANJANG, 1, 1) = '*' THEN 'NON AKTIF'
            ELSE 'BELUM TAU'                                            
        END AS FLAG,
        PRD_KODETAG AS T_IGR, 
        COALESCE(PRC_KODETAG, '.') AS T_IDM, 
        BTR_UMUR_BRG AS SELF_LIFE,
        BTR_SAT_UMUR_BRG AS SAT1,        
        CASE  
            WHEN BTR_TURUN_PAJANG = 0.5 THEN '0.5' || ' ' || BTR_SAT_TURUN_PAJANG
            WHEN BTR_TURUN_PAJANG >= 1 THEN BTR_TURUN_PAJANG || ' ' || BTR_SAT_TURUN_PAJANG
        END AS TURUN_PAJANG,        
        CASE  
            WHEN BTR_RETUR_SUPP = 0.5 THEN '0.5' || ' ' || BTR_SAT_RETUR_SUPP
            WHEN BTR_RETUR_SUPP >= 1 THEN BTR_RETUR_SUPP || ' ' || BTR_SAT_RETUR_SUPP
        END AS RETUR_SUPP,        
        CASE  
            WHEN BTR_BATAS_RETUR = 0.5 THEN '0.5' || ' ' || BTR_SAT_BATAS_RETUR
            WHEN BTR_BATAS_RETUR >= 1 THEN BTR_BATAS_RETUR || ' ' || BTR_SAT_BATAS_RETUR
        END AS BATAS_RETUR_SUPP,        
        BTR_CREATE_DT::DATE AS UPDATE_TGL
    FROM TBMASTER_BATASRETUR
    LEFT JOIN ( 
        SELECT * FROM TBMASTER_PRODMAST 
        LEFT JOIN (SELECT * FROM TBMASTER_DEPARTEMENT) joy1 ON prd_kodedepartement = dep_kodedepartement       
        LEFT JOIN (SELECT * FROM tbmaster_prodcrm WHERE PRC_GROUP = 'I') joy2 ON SUBSTRING(prd_prdcd, 1, 6) = SUBSTRING(prc_pluigr, 1, 6)   
        LEFT JOIN (SELECT * FROM tbmaster_barcode WHERE BRC_PRDCD LIKE '%1') joy3 ON SUBSTRING(brc_prdcd, 1, 6) = SUBSTRING(PRD_PRDCD, 1, 6) 
        WHERE PRD_PRDCD LIKE '%0'
    ) joy4 ON PRD_PRDCD = BTR_PRDCD
    WHERE BTR_FLAG_KESEGARAN <> 'No Expired Date'
    AND BTR_UMUR_BRG <> 0
    AND PRD_PRDCD IS NOT NULL
) fr1";
