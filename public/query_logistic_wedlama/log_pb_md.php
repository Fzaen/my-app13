<?php

$sql = "SELECT DISTINCT 
       CASE 
           WHEN STATUS IS NULL AND qty_bpb > 0 THEN 'SUDAH BTB'
           ELSE STATUS 
       END AS STATUS,
       DIV,
       DEPT,
       KATB,
       TRJD_PRDCD AS PLU,
       DESK,
       TAGIGR,
       TAGIDM,
       UNIT,
       FRAC,
       FLAG,
       TRJD_CUS_KODEMEMBER AS KODE,
       NASUP,
       NOPB,
       TGL_PB,
       QTY_PB,
       GROSS_PB,
       KETERANGANPB,
       KET_PO,
       NOPO1 AS NO_PO,
       TGL_PO,
       QTY_PO,
       GROSS_PO,
       NO_BPB,
       TGL_BPB,
       QTY_BPB,
       GROSS_BPB
FROM (
    SELECT 
        CASE 
            WHEN COALESCE(PBD_RECORDID, '0') = '1' AND COALESCE(PBD_NOPO, '0') = '0' AND pbh_TGLTRANSFER IS NOT NULL THEN 'PB TDK REALISASI'
            WHEN COALESCE(PBD_RECORDID, '0') = '1' AND COALESCE(PBD_NOPO, '0') <> '0' AND pbh_TGLTRANSFER IS NOT NULL THEN 'TERBIT PO'
            WHEN pbh_TGLTRANSFER IS NULL THEN 'BELUM TRANSFER KE MD'
            ELSE 'BELUM PROSES MD' 
        END AS STATUS,
        PRD_KODEDIVISI AS DIV,
        PRD_KODEDEPARTEMENT AS DEPT,
        PRD_KODEKATEGORIBARANG AS KATB,
        PBD_PRDCD AS TRJD_PRDCD,
        PRD_DESKRIPSIPANJANG AS DESK,
        PRD_KODETAG AS TAGIGR,
        PRC_KODETAG AS TAGIDM,
        PRD_UNIT AS UNIT,
        PRD_FRAC AS FRAC,
        CASE 
            WHEN prc_pluidm IS NOT NULL AND prd_flagidm = 'Y' THEN 'IDM ONLY'
            WHEN prc_pluidm IS NOT NULL AND prd_flagidm = 'N' THEN 'IGR IDM'
            ELSE 'IGR ONLY' 
        END AS FLAG,
        HGB_KODESUPPLIER AS TRJD_CUS_KODEMEMBER,
        SUP_NAMASUPPLIER AS NASUP,
        PBD_NOPO AS NOPO,
        PBD_NOPB AS NOPB,
        PBD_CREATE_DT AS TGL_PB,
        PBD_QTYPB AS QTY_PB,
        PBD_GROSS AS GROSS_PB,
        PBH_KETERANGANPB AS KETERANGANPB
    FROM TBTR_PB_D
    LEFT JOIN TBMASTER_PRODMAST ON PBD_PRDCD = PRD_PRDCD
    LEFT JOIN TBTR_PB_H ON PBD_NOPB = PBH_NOPB
    LEFT JOIN TBMASTER_PRODCRM ON PBD_PRDCD = PRC_PLUIGR
    LEFT JOIN TBMASTER_HARGABELI ON PBD_PRDCD = HGB_PRDCD
    LEFT JOIN TBMASTER_SUPPLIER ON HGB_KODESUPPLIER = SUP_KODESUPPLIER
--    WHERE PBD_CREATE_DT::DATE 
--    = CAST('2025-10-03' AS DATE)
) AS pb_data
LEFT JOIN (
    SELECT 
        TPOD_NOPO AS NOPO1,
        TPOD_TGLPO::DATE AS TGL_PO,
        TPOD_PRDCD,
        TPOD_QTYPO AS QTY_PO,
        TPOD_GROSS AS GROSS_PO,
        CASE 
            WHEN COALESCE(TPOH_RECORDID, '0') = '0' AND TPOD_TGLPO + INTERVAL '1 day' * TPOH_JWPB >= CURRENT_DATE THEN 'OUTSTANDING'
            WHEN COALESCE(TPOH_RECORDID, '0') = '2' AND TPOD_QTYPB IS NULL THEN 'PO TDK REALISASI'
            WHEN COALESCE(TPOH_RECORDID, '0') = '1' THEN 'BATAL'
            WHEN COALESCE(TPOH_RECORDID, '0') = '2' THEN 'SUDAH BTB'
            WHEN COALESCE(TPOH_RECORDID, '0') = 'X' THEN 'ON PROSES DCP'
            ELSE 'EXP' 
        END AS KET_PO
    FROM TBTR_PO_D
    LEFT JOIN TBTR_PO_H ON TPOD_NOPO = TPOH_NOPO
) AS po_data ON (COALESCE(NOPO, '0') || TRJD_PRDCD) = (NOPO1 || TPOD_PRDCD)
LEFT JOIN (
    SELECT 
        MSTD_PRDCD,
        MSTD_NOPO AS MSTD_NOPO,
        MSTD_NODOC AS NO_BPB,
        MSTD_TGLDOC::DATE AS TGL_BPB,
        MSTD_QTY AS QTY_BPB,
        MSTD_GROSS AS GROSS_BPB,
        CASE 
            WHEN COALESCE(MSTH_RECORDID, '0') = '1' THEN 'BATAL'
            WHEN COALESCE(MSTH_RECORDID, '0') = 'X' THEN 'ON PROSES'
            ELSE 'SUDAH BPB' 
        END AS KET_BPB
    FROM TBTR_MSTRAN_D
    LEFT JOIN TBTR_MSTRAN_H ON MSTD_NODOC = MSTH_NODOC
) AS bpb_data ON (COALESCE(NOPO, '0') || TRJD_PRDCD) = (MSTD_NOPO || MSTD_PRDCD)
where TGL_PB::date 
BETWEEN '{$ptglstart}' AND '{$ptglend}' 
    --  BETWEEN '2025-10-01' AND '2025-10-03'
  {$plusales}
  {$membersales}
ORDER BY TGL_PB,DIV, DEPT, KATB, TRJD_PRDCD";
